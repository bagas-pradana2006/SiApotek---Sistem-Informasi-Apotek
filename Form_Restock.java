    private void Ed_JumlahKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_Ed_JumlahKeyReleased
        try {
            if (Ed_Jumlah.getText().isEmpty() || Cb_Obat.getSelectedItem() == null) {
                Ed_Subtotal.setText("0");
                return;
            }
            String idObat = Cb_Obat.getSelectedItem().toString().split(" - ")[0];
            int jumlah = Integer.parseInt(Ed_Jumlah.getText());
            
            Connection conn = KoneksiDb.getKoneksi();
            PreparedStatement pst = conn.prepareStatement("SELECT harga_beli FROM obat WHERE id_obat=?");
            pst.setString(1, idObat);
            ResultSet rs = pst.executeQuery();
            
            if (rs.next()) {
                int hargaBeli = rs.getInt("harga_beli");
                Ed_Subtotal.setText(String.valueOf(hargaBeli * jumlah));
            }
        } catch (Exception e) {
            Ed_Subtotal.setText("0");
        }
    }//GEN-LAST:event_Ed_JumlahKeyReleased

    private void Btn_TambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Btn_TambahActionPerformed
        try {
            String selectedObat = Cb_Obat.getSelectedItem().toString();
            String idObat = selectedObat.split(" - ")[0];
            String namaObat = selectedObat.split(" - ")[1];
            
            int jumlah = Integer.parseInt(Ed_Jumlah.getText());
            int subtotal = Integer.parseInt(Ed_Subtotal.getText());
            int hargaBeli = subtotal / jumlah;
            
            // Masukkan ke tabel di layar
            tabMode.addRow(new Object[]{idObat, namaObat, hargaBeli, jumlah, subtotal});
            
            // Hitung total
            totalBelanja += subtotal;
            Lbl_Total.setText("Total: Rp " + totalBelanja);
            
            // Bersihkan input
            Ed_Jumlah.setText("");
            Ed_Subtotal.setText("0");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Pilih obat dan isi jumlah dengan benar!");
        }
    }//GEN-LAST:event_Btn_TambahActionPerformed

    private void Btn_SimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Btn_SimpanActionPerformed
        try {
            if (tabMode.getRowCount() == 0 || Ed_IdRestock.getText().isEmpty()) {
                JOptionPane.showMessageDialog(null, "ID Transaksi kosong atau keranjang masih kosong!");
                return;
            }
            
            Connection conn = KoneksiDb.getKoneksi();
            
            String idRestock = Ed_IdRestock.getText();
            String idSupplier = Cb_Supplier.getSelectedItem().toString().split(" - ")[0];
            String tanggal = new SimpleDateFormat("yyyy-MM-dd").format(new Date()); // Otomatis hari ini!
            
            // 1. Simpan ke transaksi_beli
            String sqlBeli = "INSERT INTO transaksi_beli VALUES (?, ?, ?, ?)";
            PreparedStatement pstBeli = conn.prepareStatement(sqlBeli);
            pstBeli.setString(1, idRestock);
            pstBeli.setString(2, tanggal);
            pstBeli.setString(3, idSupplier);
            pstBeli.setInt(4, totalBelanja);
            pstBeli.execute();
            
            // 2. Simpan ke detail_beli dan TAMBAH STOK
            for (int i = 0; i < tabMode.getRowCount(); i++) {
                String idDetail = idRestock + "-" + i;
                String idObat = Tbl_Keranjang.getValueAt(i, 0).toString();
                int jumlah = Integer.parseInt(Tbl_Keranjang.getValueAt(i, 3).toString());
                int subtotal = Integer.parseInt(Tbl_Keranjang.getValueAt(i, 4).toString());
                
                // Insert detail
                String sqlDetail = "INSERT INTO detail_beli VALUES (?, ?, ?, ?, ?)";
                PreparedStatement pstDetail = conn.prepareStatement(sqlDetail);
                pstDetail.setString(1, idDetail);
                pstDetail.setString(2, idRestock);
                pstDetail.setString(3, idObat);
                pstDetail.setInt(4, jumlah);
                pstDetail.setInt(5, subtotal);
                pstDetail.execute();
                
                // Update Stok Obat (+)
                String sqlStok = "UPDATE obat SET stok = stok + ? WHERE id_obat=?";
                PreparedStatement pstStok = conn.prepareStatement(sqlStok);
                pstStok.setInt(1, jumlah);
                pstStok.setString(2, idObat);
                pstStok.execute();
            }
            
            JOptionPane.showMessageDialog(null, "Restock Berhasil! Stok Obat sudah bertambah.");
            
            // Reset form
            Ed_IdRestock.setText("");
            tabMode.setRowCount(0);
            totalBelanja = 0;
            Lbl_Total.setText("Total: Rp 0");
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Gagal Simpan Transaksi: " + e.getMessage());
        }
    }//GEN-LAST:event_Btn_SimpanActionPerformed

