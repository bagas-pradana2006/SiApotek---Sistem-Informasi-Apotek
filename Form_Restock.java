    private void loadComboBoxes() {
        try {
            Connection conn = KoneksiDb.getKoneksi();
            Statement st = conn.createStatement();
            
            // Load Supplier
            ResultSet rsSupp = st.executeQuery("SELECT id_supplier, nama_supplier FROM supplier");
            Cb_Supplier.removeAllItems();
            while (rsSupp.next()) {
                Cb_Supplier.addItem(rsSupp.getString("id_supplier") + " - " + rsSupp.getString("nama_supplier"));
            }
            
            // Load Obat
            ResultSet rsObat = st.executeQuery("SELECT id_obat, nama_obat FROM obat");
            Cb_Obat.removeAllItems();
            while (rsObat.next()) {
                Cb_Obat.addItem(rsObat.getString("id_obat") + " - " + rsObat.getString("nama_obat"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error load combobox: " + e.getMessage());
        }
    }

