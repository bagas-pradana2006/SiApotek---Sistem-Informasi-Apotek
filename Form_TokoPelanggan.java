    private void Ed_SubtotalKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_Ed_SubtotalKeyReleased
        try {
            if (Ed_Jumlah.getText().isEmpty() || Cb_Obat.getSelectedItem() == null) {
                Ed_Subtotal.setText("0");
                return;
            }
            String idObat = Cb_Obat.getSelectedItem().toString().split(" - ")[0];
            int jumlah = Integer.parseInt(Ed_Jumlah.getText());
            
            Connection conn = KoneksiDb.getKoneksi();
            PreparedStatement pst = conn.prepareStatement("SELECT harga_jual FROM obat WHERE id_obat=?");
            pst.setString(1, idObat);
            ResultSet rs = pst.executeQuery();
            
            if (rs.next()) {
                int hargaJual = rs.getInt("harga_jual");
                Ed_Subtotal.setText(String.valueOf(hargaJual * jumlah));
            }
        } catch (Exception e) {
            Ed_Subtotal.setText("0");
        }
    }//GEN-LAST:event_Ed_SubtotalKeyReleased

    private void Btn_TambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Btn_TambahActionPerformed
        try {
            String selectedObat = Cb_Obat.getSelectedItem().toString();
            String idObat = selectedObat.split(" - ")[0];
            String namaObat = selectedObat.split(" - ")[1];
            
            int jumlah = Integer.parseInt(Ed_Jumlah.getText());
            int subtotal = Integer.parseInt(Ed_Subtotal.getText());
            int harga = subtotal / jumlah;
            
            tabMode.addRow(new Object[]{idObat, namaObat, harga, jumlah, subtotal});
            
            totalBelanja += subtotal;
            Lbl_Total.setText("Total Belanja: Rp " + totalBelanja);
            
            Ed_Jumlah.setText("");
            Ed_Subtotal.setText("0");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Isi jumlah dengan benar!");
        }
    }//GEN-LAST:event_Btn_TambahActionPerformed

    private void Btn_BayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Btn_BayarActionPerformed
        try {
            if (tabMode.getRowCount() == 0) {
                JOptionPane.showMessageDialog(null, "Keranjang belanja masih kosong!");
                return;
            }
            
            Connection conn = KoneksiDb.getKoneksi();
            // Buat ID Transaksi acak untuk pelanggan
            String idTransaksi = "TRX" + (System.currentTimeMillis() % 10000); 
            String pembeli = UserSession.getUsername(); // Ambil username yang sedang login
            String tanggal = new SimpleDateFormat("yyyy-MM-dd").format(new Date());
            
            // 1. Simpan ke transaksi_jual
            String sqlJual = "INSERT INTO transaksi_jual VALUES (?, ?, ?, 'Pelanggan Mandiri', ?)";
            PreparedStatement pstJual = conn.prepareStatement(sqlJual);
            pstJual.setString(1, idTransaksi);
            pstJual.setString(2, tanggal);
            pstJual.setString(3, pembeli);
            pstJual.setInt(4, totalBelanja);
            pstJual.execute();
            
            // 2. Simpan ke detail_jual dan KURANGI STOK
            for (int i = 0; i < tabMode.getRowCount(); i++) {
                String idDetail = idTransaksi + "-" + i;
                String idObat = Tbl_Keranjang.getValueAt(i, 0).toString();
                int jumlah = Integer.parseInt(Tbl_Keranjang.getValueAt(i, 3).toString());
                int subtotal = Integer.parseInt(Tbl_Keranjang.getValueAt(i, 4).toString());
                
                String sqlDetail = "INSERT INTO detail_jual VALUES (?, ?, ?, ?, ?)";
                PreparedStatement pstDetail = conn.prepareStatement(sqlDetail);
                pstDetail.setString(1, idDetail);
                pstDetail.setString(2, idTransaksi);
                pstDetail.setString(3, idObat);
                pstDetail.setInt(4, jumlah);
                pstDetail.setInt(5, subtotal);
                pstDetail.execute();
                
                // Update Stok Obat (-)
                String sqlStok = "UPDATE obat SET stok = stok - ? WHERE id_obat=?";
                PreparedStatement pstStok = conn.prepareStatement(sqlStok);
                pstStok.setInt(1, jumlah);
                pstStok.setString(2, idObat);
                pstStok.execute();
            }
            
            JOptionPane.showMessageDialog(null, "Pembayaran Berhasil! Terima kasih sudah berbelanja.");
            
            // Reset
            tabMode.setRowCount(0);
            totalBelanja = 0;
            Lbl_Total.setText("Total Belanja: Rp 0");
            loadObat(); // Refresh agar obat yg habis hilang dari pilihan
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Gagal Checkout: " + e.getMessage());
        }
    }//GEN-LAST:event_Btn_BayarActionPerformed

