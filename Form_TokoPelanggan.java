    private void loadObat() {
        try {
            Connection conn = KoneksiDb.getKoneksi();
            Statement st = conn.createStatement();
            // Hanya tampilkan obat yang stoknya masih ada
            ResultSet rs = st.executeQuery("SELECT id_obat, nama_obat FROM obat WHERE stok > 0");
            Cb_Obat.removeAllItems();
            while (rs.next()) {
                Cb_Obat.addItem(rs.getString("id_obat") + " - " + rs.getString("nama_obat"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error load obat: " + e.getMessage());
        }
    }

